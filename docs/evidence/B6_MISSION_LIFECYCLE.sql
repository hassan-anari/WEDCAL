CREATE FUNCTION clans_mission_lifecycle_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.history_unknown_before IS NOT NULL THEN
            RAISE EXCEPTION 'New definitions cannot invent legacy activation history';
        END IF;
        NEW.activation_revision := CASE WHEN NEW.enabled THEN 1 ELSE 0 END;
    ELSE
        IF OLD.history_unknown_before IS DISTINCT FROM NEW.history_unknown_before THEN
            RAISE EXCEPTION 'Mission history cutover is immutable';
        END IF;
        NEW.activation_revision := OLD.activation_revision +
            CASE WHEN OLD.enabled IS DISTINCT FROM NEW.enabled THEN 1 ELSE 0 END;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER b6_mission_lifecycle_revision BEFORE INSERT OR UPDATE
ON clans_clanmissiondefinition FOR EACH ROW EXECUTE FUNCTION clans_mission_lifecycle_revision();

CREATE FUNCTION clans_mission_lifecycle_transition() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE effective_at timestamptz := clock_timestamp();
BEGIN
    IF TG_OP = 'UPDATE' AND OLD.enabled = NEW.enabled THEN
        RETURN NEW;
    END IF;
    IF NEW.enabled THEN
        IF EXISTS (SELECT 1 FROM clans_clanmissionactivation
            WHERE definition_id = NEW.id AND ends_at > effective_at) THEN
            RAISE EXCEPTION 'Mission lifecycle clock moved backwards';
        END IF;
        INSERT INTO clans_clanmissionactivation (definition_id, starts_at, ends_at, origin)
            VALUES (NEW.id, effective_at, NULL, 'STATE_TRANSITION');
    ELSIF TG_OP = 'UPDATE' THEN
        UPDATE clans_clanmissionactivation SET ends_at = effective_at
            WHERE definition_id = NEW.id AND ends_at IS NULL;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Enabled mission has no open activation interval';
        END IF;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER b6_mission_lifecycle_transition AFTER INSERT OR UPDATE
ON clans_clanmissiondefinition FOR EACH ROW EXECUTE FUNCTION clans_mission_lifecycle_transition();

CREATE FUNCTION clans_mission_interval_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF pg_trigger_depth() < 2 OR TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Mission intervals are owned by definition transitions';
    END IF;
    IF TG_OP = 'UPDATE' AND (OLD.ends_at IS NOT NULL OR NEW.ends_at IS NULL OR
        ROW(OLD.definition_id, OLD.starts_at, OLD.origin) IS DISTINCT FROM
        ROW(NEW.definition_id, NEW.starts_at, NEW.origin)) THEN
        RAISE EXCEPTION 'Mission activation evidence is immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER b6_mission_interval_guard BEFORE INSERT OR UPDATE OR DELETE
ON clans_clanmissionactivation FOR EACH ROW EXECUTE FUNCTION clans_mission_interval_guard();


